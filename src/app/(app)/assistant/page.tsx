"use client";

import { useEffect, useRef, useState } from "react";
import { Bot, Send, User } from "lucide-react";
import { Card } from "@/components/ui/card";
import { generateAssistantReply, suggestedPrompts } from "@/lib/assistant-responses";
import type { ChatMessage } from "@/lib/data/types";
import { DemoBanner } from "@/components/layout/demo-banner";
import { cn } from "@/lib/utils";

export default function AssistantPage() {
  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      id: "m0",
      role: "assistant",
      content:
        "Hi, I'm your simulated demo assistant. I answer from a fixed sample dataset, not a live model. Ask about your projects, win rate, or top match.",
      createdAt: new Date().toISOString(),
    },
  ]);
  const [input, setInput] = useState("");
  const [thinking, setThinking] = useState(false);
  const scrollRef = useRef<HTMLDivElement>(null);
  const nextId = useRef(1);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
  }, [messages, thinking]);

  function send(text: string) {
    if (!text.trim()) return;
    const userMsg: ChatMessage = {
      id: `u_${nextId.current++}`,
      role: "user",
      content: text,
      createdAt: new Date().toISOString(),
    };
    setMessages((prev) => [...prev, userMsg]);
    setInput("");
    setThinking(true);
    setTimeout(() => {
      setMessages((prev) => [
        ...prev,
        {
          id: `a_${nextId.current++}`,
          role: "assistant",
          content: generateAssistantReply(text),
          createdAt: new Date().toISOString(),
        },
      ]);
      setThinking(false);
    }, 700);
  }

  return (
    <div className="max-w-3xl space-y-4 flex flex-col h-[calc(100vh-8rem)]">
      <div>
        <h1 className="font-display text-2xl font-semibold">AI Assistant</h1>
        <p className="text-sm text-ink-muted mt-1">Ask questions about your demo workspace.</p>
      </div>

      <DemoBanner>
        Simulated assistant — replies are generated by keyword-matching this demo&rsquo;s mock
        dataset, not by a live language model.
      </DemoBanner>

      <Card className="flex-1 flex flex-col min-h-0">
        <div ref={scrollRef} className="flex-1 overflow-y-auto scrollbar-thin p-5 space-y-4">
          {messages.map((m) => (
            <div key={m.id} className={cn("flex gap-3", m.role === "user" && "flex-row-reverse")}>
              <div
                className={cn(
                  "flex h-8 w-8 shrink-0 items-center justify-center rounded-full",
                  m.role === "assistant" ? "bg-brand-soft text-brand-strong" : "bg-surface-muted text-ink-muted",
                )}
              >
                {m.role === "assistant" ? <Bot className="h-4 w-4" /> : <User className="h-4 w-4" />}
              </div>
              <div
                className={cn(
                  "max-w-[75%] rounded-lg px-4 py-2.5 text-sm leading-relaxed",
                  m.role === "assistant" ? "bg-surface-muted" : "bg-brand text-white",
                )}
              >
                {m.content}
              </div>
            </div>
          ))}
          {thinking ? (
            <div className="flex gap-3">
              <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-brand-soft text-brand-strong">
                <Bot className="h-4 w-4" />
              </div>
              <div className="rounded-lg bg-surface-muted px-4 py-2.5 text-sm text-ink-muted">Thinking…</div>
            </div>
          ) : null}
        </div>

        <div className="border-t border-border p-4 space-y-3">
          <div className="flex flex-wrap gap-2">
            {suggestedPrompts.map((p) => (
              <button
                key={p}
                onClick={() => send(p)}
                className="rounded-full border border-border px-3 py-1 text-xs text-ink-muted hover:text-ink hover:border-brand/40"
              >
                {p}
              </button>
            ))}
          </div>
          <form
            onSubmit={(e) => {
              e.preventDefault();
              send(input);
            }}
            className="flex gap-2"
          >
            <input
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Ask something…"
              className="flex-1 h-10 rounded-md border border-border bg-background px-3 text-sm outline-none focus:border-brand"
            />
            <button
              type="submit"
              className="flex h-10 w-10 items-center justify-center rounded-md bg-brand text-white hover:bg-brand-strong"
            >
              <Send className="h-4 w-4" />
            </button>
          </form>
        </div>
      </Card>
    </div>
  );
}
